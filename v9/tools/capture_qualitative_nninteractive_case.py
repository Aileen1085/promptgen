"""Observe one authorized native full-mask evaluation in a fresh process.

No inference implementation or model modification lives here. The unchanged
worker restores weights, predicts and completes normally. Its full-volume
metric call supplies the observed final mask and target. Only mask.npy and
provenance.json are exported; original workers retain their usual metric audits.

Manifest v1 fields: method, task, authorized_tasks (one key for each of five
sources), reference (original row with all ten metrics), shape_dhw,
grid_verification (verified/grid_id/axes_dhw/evidence), job_path, output_dir,
gpu_uuid, source_sha256 and input_sha256 (path->SHA256). Paths are relative to
this manifest. Caller must bind the physically verified native output grid and
the original fixed paper protocol. This tool does not infer affine alignment.
Native job: tasks=[task], output=<new original-worker metrics directory>.
nnInteractive job: model=nninteractive, prepared/run/source/gpu/frame_batch;
prepared manifest must contain only task and existing refs must be supplied.
Its gpu is the original CLI's physical integer index; nvidia-smi must map that
index to manifest gpu_uuid before CUDA initialization and before delegation.
PAM job signature must be generated by the appropriate unchanged controller.
Run once per process; never use existing production job/output directories.
"""
import argparse
from contextlib import contextmanager, ExitStack
import hashlib
import importlib
import json
import math
import os
from pathlib import Path
import subprocess
import sys

import numpy as np

ROOT = Path(__file__).absolute().parents[1]
SOURCES = ('amos', 'magic', 'kits23', 'msd_task10', 'msd_task07')
METHODS = ('nnInteractive', 'SAM2', 'MedSAM2', 'SAM-Med3D Turbo', 'SegVol', 'VISTA3D', 'PAM')
METRICS = ('dice', 'mean_slice_dice', 'iou', 'precision', 'recall', 'specificity',
           'pred_gt_ratio', 'mean_slice_nsd_1mm', 'mean_slice_nsd_2mm', 'mean_slice_nsd_3mm')


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def sha(path):
    result = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            result.update(block)
    return result.hexdigest()


def key(row):
    source, case = row['source_name'], row['case_id']
    cid = row.get('global_class_id', row.get('class_id'))
    if not isinstance(source, str) or not isinstance(case, str) or not case:
        raise ValueError('invalid exact task key')
    if isinstance(cid, bool) or not isinstance(cid, int):
        raise ValueError('global class ID must be an integer')
    return source, case, cid


def validate_scope(spec):
    if spec.get('schema_version') != 1 or spec.get('method') not in METHODS:
        raise ValueError('native capture schema/method mismatch')
    authorized = [key(t) for t in spec['authorized_tasks']]
    if len(authorized) != 5 or len(set(authorized)) != 5 or {k[0] for k in authorized} != set(SOURCES):
        raise ValueError('authorization requires exactly five source case-class keys')
    if key(spec['task']) not in authorized:
        raise ValueError('task outside frozen five-case authorization')
    shape = spec['shape_dhw']
    if len(shape) != 3 or any(type(n) is not int or n <= 0 for n in shape):
        raise ValueError('invalid full-grid shape')
    grid = spec['grid_verification']
    if (grid.get('verified') is not True or grid.get('axes_dhw') not in ('ZXY', 'ZYX')
            or not isinstance(grid.get('grid_id'), str) or not grid['grid_id'].strip()
            or not isinstance(grid.get('evidence'), str) or not grid['evidence'].strip()):
        raise ValueError('physical export grid attestation required')


def compare_reference(row, reference):
    if key(row) != key(reference):
        raise ValueError('original result task key mismatch')
    for name in METRICS:
        values = [float(item[name]) for item in (row, reference)]
        if not all(math.isfinite(v) for v in values) or abs(values[0] - values[1]) > 1e-6:
            raise ValueError('original reference metric mismatch: ' + name)


def validate_task_details(expected, actual):
    if key(expected) != key(actual):
        raise ValueError('immutable task key mismatch')
    for name in ('image', 'label', 'local_class_id', 'class_name', 'prompt_cache_name'):
        if name not in expected or name not in actual or expected[name] != actual[name]:
            raise ValueError('immutable task detail mismatch: ' + name)


def verify_inventory(expected, required, base):
    inventory = {str((Path(base) / name).absolute()): digest for name, digest in expected.items()}
    missing = [str(Path(path).absolute()) for path in required if str(Path(path).absolute()) not in inventory]
    if missing:
        raise ValueError('mandatory inventory bindings missing: ' + repr(missing))
    for name, digest in inventory.items():
        if sha(name) != digest:
            raise ValueError('source/input SHA mismatch: ' + name)
    return inventory


def background_binding(spec, job, package):
    """Match CaseLoader's exact label-stat/prompt/shape key; never create it."""
    task = spec['task']
    split = read(ROOT / 'configs/ct13_v10_2_split_20260928.json')
    entry = next(r for r in split['datasets'][task['source_name']]['val'] if r['case_id'] == task['case_id'])
    label = Path(entry.get('label', entry.get('label_path')))
    stamp = (ROOT / label).stat()
    payload = dict(version='v9_training_vertical_bg_v1', margin_ratio=.08,
                   foreground_package_sha256=sha(package), shape=list(spec['shape_dhw']),
                   label_signature=[str(label), stamp.st_size, stamp.st_mtime_ns])
    signature = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    if spec['method'] in ('SAM2', 'MedSAM2'):
        directory = ROOT / job['background_cache_dir']
    else:
        directory = ROOT / 'output/native_sam2_amos_sparse_bg_pilot_20261007/background_scribbles_light'
    path = directory / (signature + '.npz')
    if not path.is_file():
        raise ValueError('required existing background cache missing: ' + str(path))
    with np.load(path, allow_pickle=False) as archive:
        if str(archive['signature'].item()) != signature:
            raise ValueError('existing background cache signature mismatch')
    return path


def required_bindings(spec, job, job_path):
    """Derive actual dependencies rather than trusting caller-provided path lists."""
    method, task = spec['method'], spec['task']
    sources = [Path(__file__), ROOT / 'utils/metrics.py']
    inputs = [job_path, ROOT / 'configs/ct13_v10_2_split_20260928.json',
              ROOT / task['image'], ROOT / task['label']]
    cache = ROOT / 'v10/.cache/totalseg_sam2_promptgen_v10_prompt_roi_full_v1'
    package = cache / 'metadata/shared_adaptive_prompt_v1' / task['source_name'] / task['prompt_cache_name']
    inputs.append(package)
    with np.load(package, allow_pickle=False) as archive:
        case_path = cache / '_case_images_v1' / str(archive['case_image_name'].item())
    if case_path.is_file():
        inputs.append(case_path)
    if method in ('SAM2', 'MedSAM2', 'SAM-Med3D Turbo', 'SegVol', 'VISTA3D'):
        inputs.append(background_binding(spec, job, package))
    if task['source_name'] == 'magic':
        split = read(ROOT / 'configs/ct13_v10_2_split_20260928.json')
        entry = next(r for r in split['datasets']['magic']['val'] if r['case_id'] == task['case_id'])
        inputs += [ROOT / entry.get('image', entry.get('image_path')),
                   ROOT / entry.get('label', entry.get('label_path'))]
    if method == 'nnInteractive':
        prepared = ROOT / job['prepared']
        inputs += [prepared / 'manifest.json', prepared / 'refs.json']
        folder = ROOT.parent / 'nninteractive_test_amos/infer'
        if not (folder / 'infer_3d_point_common.py').is_file():
            folder = ROOT / 'nninteractive_test/infer'
        sources += [ROOT / 'tools/ct13_full_validation_eval.py', folder / 'infer_eight_source_adaptive_nninteractive.py',
                    folder / 'eight_source_adaptive_protocol.py', ROOT / 'v9_2_adaptive_scribble.py']
        model = ROOT.parent / 'nninteractive_test_amos/checkpoints/nnInteractive_v1.0'
        checkpoints = sorted(model.rglob('checkpoint_final.pth'))
        if not checkpoints:
            raise ValueError('original nnInteractive checkpoint folder missing')
        inputs += checkpoints + [model / 'dataset.json', model / 'plans.json']
    else:
        sources += [ROOT / 'tools/native_ct13_eval.py', ROOT / 'tools/native_sam2_physical_eval.py',
                    ROOT / 'infer/native_sam2_physical_prompts.py']
        if method in ('SAM2', 'MedSAM2'):
            if method == 'SAM2':
                code, config, weight = 'sam2', 'configs/sam2.1/sam2.1_hiera_l.yaml', 'sam2/checkpoints/sam2.1_hiera_large.pt'
            else:
                code = 'third_party/MedSAM2_official_20261007'
                if not (ROOT / code / 'sam2/build_sam.py').is_file():
                    code = 'MedSAM2'
                config, weight = 'configs/sam2.1_hiera_t512.yaml', 'MedSAM2/checkpoints/MedSAM2_latest.pt'
            sources += [ROOT / code / 'sam2/build_sam.py', ROOT / code / 'sam2/sam2_video_predictor.py', ROOT / code / 'sam2' / config]
            inputs.append(ROOT / weight)
        elif method == 'PAM':
            sources += [ROOT / ('tools/' + name + '.py') for name in ('pam_nine_source_probability', 'pam_soft_fusion', 'pam_amos_three_view')]
            assets = ROOT / 'third_party/PAM_official_20261010/checkpoints'
            inputs += [assets / 'box2mask.pth', assets / 'propmask.pth',
                       ROOT / 'output/native_sam2_medsam2_ct13_full6094_20261007_gridfix/manifest.json']
            if task['source_name'] == 'amos':
                sources.append(ROOT / 'tools/pam_amos_probability_full.py')
                inputs.append(ROOT / 'output/pam_amos_soft_fusion_pilot119_20261023/merged_metrics.json')
        else:
            stem, weight = {
                'SAM-Med3D Turbo': ('sammed3d', 'third_party/SAM_Med3D_official_20261007/checkpoints/sam_med3d_turbo.pth'),
                'SegVol': ('segvol', 'segvol-3d/weights/pytorch_model.bin'),
                'VISTA3D': ('vista3d', 'vista3d/official_weights/model_monai1.3.pt')}[method]
            sources += [ROOT / ('tools/native_' + stem + '_ct13.py'), ROOT / ('tools/native_' + stem + '_pilot.py'),
                        ROOT / ('infer/native_' + stem + '_prompts.py'), ROOT / 'tools/native_sammed3d_ct13.py',
                        ROOT / 'tools/native_sammed3d_pilot.py', ROOT / 'infer/native_sammed3d_prompts.py']
            inputs.append(ROOT / weight)
            if method == 'VISTA3D':
                sources.append(ROOT / 'vista3d/official_loader.py')
    return sources, inputs


def array(value):
    if hasattr(value, 'detach'):
        value = value.detach().cpu().numpy()
    return np.asarray(value)


class MaskObserver:
    def __init__(self, shape):
        self.shape = tuple(shape)
        self.mask = None
        self.target_digest = None
        self.full_calls = 0
        self.metrics = None
        self.dice = None

    def record(self, prediction, target, metrics):
        p, t = array(prediction), array(target)
        if p.shape != self.shape or t.shape != self.shape:
            return  # Native SAM2 also measures the supported-frame subset.
        for value in (p, t):
            if not np.isfinite(value).all() or not ((value == 0) | (value == 1)).all():
                raise ValueError('native full mask/target must be finite binary')
        total = int(np.count_nonzero(p)) + int(np.count_nonzero(t))
        if not np.count_nonzero(t):
            raise ValueError('selected full target must be nonempty')
        dice = 2. * int(np.count_nonzero((p != 0) & (t != 0))) / total
        if not math.isfinite(float(metrics['dice'])) or abs(dice - float(metrics['dice'])) > 1e-6:
            raise ValueError('observed full-mask Dice does not match original scorer')
        digest = hashlib.sha256(np.ascontiguousarray(t, dtype=np.uint8).tobytes()).hexdigest()
        if self.mask is not None and (not np.array_equal(self.mask, p) or self.target_digest != digest):
            raise ValueError('conflicting full-volume predictions/targets in single-task capture')
        self.mask = np.array(p, dtype=np.uint8, copy=True)
        self.target_digest, self.dice = digest, dice
        self.metrics = dict(metrics)
        self.full_calls += 1


@contextmanager
def patch(owner, name, value):
    original = getattr(owner, name)
    setattr(owner, name, value)
    try:
        yield
    finally:
        setattr(owner, name, original)


@contextmanager
def observe_metric_factory(owner, name, observer):
    factory = getattr(owner, name)
    with ExitStack() as stack:
        seen = set()
        def wrapped(*args, **kwargs):
            metric = factory(*args, **kwargs)
            if id(metric) not in seen:
                seen.add(id(metric))
                original = metric.binary_prompt_metrics_from_masks
                def score(prediction, target, *a, **kw):
                    result = original(prediction, target, *a, **kw)
                    observer.record(prediction, target, result)
                    return result
                stack.enter_context(patch(metric, 'binary_prompt_metrics_from_masks', score))
            return metric
        stack.enter_context(patch(owner, name, wrapped))
        yield


@contextmanager
def observe_native(native, observer):
    factory = native.base_module
    with ExitStack() as stack:
        seen = set()
        def base(*args, **kwargs):
            value = factory(*args, **kwargs)
            if id(value) not in seen:
                seen.add(id(value))
                stack.enter_context(observe_metric_factory(value, 'metric_module', observer))
            return value
        stack.enter_context(patch(native, 'base_module', base))
        yield


def save_capture(output, observer, metadata):
    if observer.mask is None:
        raise ValueError('original evaluation never exposed a full-volume final mask')
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    with (output / 'mask.npy').open('xb') as stream:
        np.save(stream, observer.mask, allow_pickle=False)
    info = dict(metadata, mask_sha256=sha(output / 'mask.npy'), shape_dhw=list(observer.shape),
                dtype='uint8', observed_full_metric_calls=observer.full_calls,
                target_binary_sha256=observer.target_digest, dice_3d=observer.dice)
    with (output / 'provenance.json').open('x', encoding='utf-8') as stream:
        json.dump(info, stream, indent=2, ensure_ascii=False, allow_nan=False)
        stream.write('\n')


def gpu_free_memory(uuid):
    inventory = subprocess.check_output(['nvidia-smi', '--query-gpu=uuid,memory.free',
                                         '--format=csv,noheader,nounits'], text=True)
    matches = [line.split(',') for line in inventory.splitlines() if line.split(',')[0].strip() == uuid]
    if len(matches) != 1:
        raise ValueError('GPU UUID missing from physical inventory')
    return int(matches[0][1])


def validate_nn_gpu_index(index, uuid):
    if type(index) is not int or index < 0:
        raise ValueError('nnInteractive job GPU must be a physical integer index')
    inventory = subprocess.check_output(['nvidia-smi', '--query-gpu=index,uuid',
                                         '--format=csv,noheader,nounits'], text=True)
    matches = []
    for line in inventory.splitlines():
        physical, actual_uuid = [value.strip() for value in line.split(',')]
        if int(physical) == index:
            matches.append(actual_uuid)
    if matches != [uuid]:
        raise ValueError('nnInteractive physical GPU index/UUID mismatch')
    return dict(physical_index=index, gpu_uuid=uuid)


def cuda_probe(uuid):
    os.environ['CUDA_VISIBLE_DEVICES'] = uuid
    import torch
    actual = str(torch.cuda.get_device_properties(0).uuid).replace('GPU-', '')
    if actual != uuid.replace('GPU-', ''):
        raise ValueError('CUDA UUID mapping mismatch')
    value = torch.ones(1, device='cuda')
    try:
        if value.item() != 1.:
            raise ValueError('CUDA tensor probe failed')
    finally:
        del value
        torch.cuda.empty_cache()
    return dict(actual_cuda_uuid=actual, cuda_tensor_probe=True)


def resource_check(uuid, minimum_free=30720):
    if type(minimum_free) is not int or minimum_free < 30720:
        raise ValueError('minimum free memory must be at least 30720 MiB')
    before = gpu_free_memory(uuid)
    if before < minimum_free:
        raise ValueError('insufficient free memory before CUDA initialization')
    probe = cuda_probe(uuid)
    after = gpu_free_memory(uuid)
    if after < minimum_free:
        raise ValueError('insufficient free memory after CUDA probe')
    return dict(gpu_uuid=uuid, minimum_free_mib=minimum_free, free_before_cuda_mib=before,
                free_after_cuda_mib=after, **probe)


def run_delegate(method, job_path, job, uuid, observer):
    sys.path.insert(0, str(ROOT))
    if method == 'nnInteractive':
        from tools import ct13_full_validation_eval as common
        with observe_metric_factory(common, 'metric_module', observer):
            common.run_model(job)
    else:
        from tools import native_ct13_eval as native
        if method in ('SAM2', 'MedSAM2'):
            worker = native.worker
        elif method == 'PAM':
            if job['tasks'][0]['source_name'] == 'amos':
                from tools import pam_amos_probability_full as controller
                controller.configure()
            else:
                from tools import pam_nine_source_probability as controller
            worker = controller.worker
        else:
            module = {'SAM-Med3D Turbo': 'native_sammed3d_ct13', 'SegVol': 'native_segvol_ct13',
                      'VISTA3D': 'native_vista3d_ct13'}[method]
            worker = importlib.import_module('tools.' + module).worker
        with observe_native(native, observer):
            worker(str(job_path), uuid)


def capture(manifest_path):
    manifest_path = Path(manifest_path).absolute()
    spec = read(manifest_path)
    validate_scope(spec)
    base = manifest_path.parent
    job_path, output = base / spec['job_path'], base / spec['output_dir']
    job = read(job_path)
    method = spec['method']
    tasks = read(ROOT / job['prepared'] / Path('manifest.json'))['tasks'] if method == 'nnInteractive' else job['tasks']
    if len(tasks) != 1 or key(tasks[0]) != key(spec['task']) or key(spec['reference']) != key(spec['task']):
        raise ValueError('delegate job/reference must contain only the authorized task')
    if method in ('SAM2', 'MedSAM2') and job.get('model') != method.lower():
        raise ValueError('native SAM2/MedSAM2 job model mismatch')
    if method == 'nnInteractive' and job.get('model') != 'nninteractive':
        raise ValueError('nnInteractive job model mismatch')
    gpu_binding = validate_nn_gpu_index(job.get('gpu'), spec['gpu_uuid']) if method == 'nnInteractive' else None
    actual = dict(tasks[0])
    if method == 'nnInteractive':
        refs = read(ROOT / job['prepared'] / Path('refs.json'))['per_case_class']
        if len(refs) != 1 or key(refs[0]) != key(spec['task']):
            raise ValueError('nnInteractive prompt refs must contain exactly the authorized task')
        actual['prompt_cache_name'] = refs[0]['prompt_cache_name']
    validate_task_details(spec['task'], actual)
    run = ROOT / (job['run'] if method == 'nnInteractive' else job['output'])
    if output.exists() or run.exists():
        raise FileExistsError('capture and original worker outputs must both be new')
    compare_reference(spec['reference'], spec['reference'])
    sources, inputs = required_bindings(spec, job, job_path)
    inventory = verify_inventory(spec['source_sha256'], sources, base)
    inventory.update(verify_inventory(spec['input_sha256'], inputs, base))
    before_job, before_manifest = sha(job_path), sha(manifest_path)
    minimum = spec.get('minimum_free_mib', 30720)
    if type(minimum) is not int or minimum < 30720:
        raise ValueError('minimum free memory must be at least 30720 MiB')
    resource = resource_check(spec['gpu_uuid'], minimum)
    observer = MaskObserver(spec['shape_dhw'])
    previous, previous_cwd = list(sys.argv), Path.cwd()
    try:
        os.chdir(ROOT)
        free = gpu_free_memory(spec['gpu_uuid'])
        if free < minimum:
            raise ValueError('insufficient free memory immediately before native delegate')
        resource['free_before_delegate_mib'] = free
        if method == 'nnInteractive':
            if validate_nn_gpu_index(job['gpu'], spec['gpu_uuid']) != gpu_binding:
                raise ValueError('nnInteractive physical GPU mapping changed before delegate')
            resource['nninteractive_gpu_binding'] = gpu_binding
        run_delegate(method, job_path, job, spec['gpu_uuid'], observer)
    finally:
        sys.argv = previous
        os.chdir(previous_cwd)
    rows = read(run / 'complete_metrics.json')['per_case_class']
    if len(rows) != 1:
        raise ValueError('normal completion must contain exactly one task')
    compare_reference(rows[0], spec['reference'])
    if observer.mask is None:
        raise ValueError('no actual final full mask captured')
    compare_reference(dict(spec['task'], **observer.metrics), spec['reference'])
    if sha(job_path) != before_job or sha(manifest_path) != before_manifest:
        raise ValueError('capture manifest/job changed during inference')
    for name, digest in inventory.items():
        if sha(name) != digest:
            raise ValueError('signed source/input changed during inference: ' + name)
    save_capture(output, observer, dict(schema_version=1, method=method, task=spec['task'],
        normal_completion=True, reference=spec['reference'], actual_row=rows[0],
        grid_verification=spec['grid_verification'], resource=resource, source_and_input_sha256=inventory,
        manifest_sha256=before_manifest, job_sha256=before_job, observer_sha256=sha(__file__),
        worker_complete_metrics_sha256=sha(run / 'complete_metrics.json')))
    return output


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', required=True, type=Path)
    args = parser.parse_args(argv)
    print('NATIVE_CAPTURE_COMPLETE', capture(args.manifest))


if __name__ == '__main__':
    main()
